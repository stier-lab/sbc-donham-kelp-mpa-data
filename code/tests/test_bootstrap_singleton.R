x <- data.frame(size=60,count=1)
set.seed(1)
one <- bootstrap_biomass(1,1,x,bio_lobster)
many <- bootstrap_biomass(7,1,x,bio_lobster)
stopifnot(abs(one$biomass-bio_lobster(60))<1e-10,one$se==0,
          abs(many$biomass-7*bio_lobster(60))<1e-10,many$se<1e-10)
zero <- bootstrap_biomass(0,integer(),x,bio_lobster)
missing <- bootstrap_biomass(1,integer(),x,bio_lobster)
stopifnot(zero$biomass==0,is.na(missing$biomass))
x <- data.frame(size=c(60,90),count=c(1,2))
set.seed(1)
mixed <- bootstrap_biomass(20,1:2,x,bio_lobster,n_resamples=10000)
expected <- 20*weighted.mean(bio_lobster(x$size),x$count)
stopifnot(abs(mixed$biomass-expected)<5*mixed$se/sqrt(10000))
cat("PASS: singleton length retained, repeated draws constant, zero/missing handling and weighted multi-size expectation\n")
